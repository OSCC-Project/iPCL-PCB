void hhSerialSendByte(uint8_t Byte){
	HAL_UART_Transmit(&huart1, &Byte, 1,HAL_MAX_DELAY);
}
void hhSerialSendString(char * mString){
	for(uint16_t i=0;mString[i]!='\0';i++){
	hhSerialSendByte(mString[i]);
}
}
