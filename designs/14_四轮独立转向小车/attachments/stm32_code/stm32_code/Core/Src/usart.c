void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart){
	if (huart == &huart1){
	static uint8_t RxState = 0;
	static uint8_t pRxPacket = 0;
	uint8_t RxData=ByteRecv;
	if (RxState == 0)
	{
		if (RxData == 0xFF)
		{
			RxState = 4;
		}
	}
	else if (RxState == 4)
	{
		if (RxData == 0xFF)
			{
				RxState = 1;
				pRxPacket = 0;
			}
	}
	else if (RxState == 1)
	{
		Serial_RxPacket[pRxPacket] = RxData;
		pRxPacket ++;
		if (pRxPacket >= 3)
		{
			RxState = 2;
		}
	}
	else if (RxState == 2)
	{
		if (RxData == 0xFE)
		{
			RxState = 0;
			Serial_RxFlag = 1;
		}
	}
	HAL_UART_Receive_IT(&huart1, &ByteRecv, 1);
	}
	}


