static void ConfigDAC(void);                                       //配置DAC

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：ConfigDAC
* 函数功能：配置DAC
* 输入参数：void 
* 输出参数：void
* 返 回 值：void
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static void ConfigDAC(void)
{
  //使能RCU相关时钟
  rcu_periph_clock_enable(RCU_GPIOA);  //使能GPIOA的时钟
  rcu_periph_clock_enable(RCU_DAC);    //使能DAC的时钟
  
  //设置GPIO输出模式及速度 PA5
  gpio_mode_set(GPIOA,GPIO_MODE_ANALOG,GPIO_PUPD_NONE,GPIO_PIN_5);
  gpio_output_options_set(GPIOA,GPIO_OTYPE_PP,GPIO_OSPEED_50MHZ,GPIO_PIN_5);

  //DAC配置
  dac_deinit(DAC0);                                           //复位DAC模块
  dac_concurrent_disable(DAC0);                               //并发DAC模式禁能
  dac_output_buffer_enable(DAC0,DAC_OUT1);                         //使能输出缓冲区
  dac_trigger_disable(DAC0,DAC_OUT1);                              //使能外部触发源
  dac_wave_mode_config(DAC0,DAC_OUT1, DAC_WAVE_DISABLE);           //禁用Wave mode

  //使能DAC
  dac_enable(DAC0,DAC_OUT1);
}

/*********************************************************************************************************
*                                              API函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：InitDAC
* 函数功能：初始化DAC模块
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
void InitDAC(void)
{
  ConfigDAC();      //配置DAC
	SetDAC(100);			//设置DAC输出值
}

/*********************************************************************************************************
* 函数名称：SetDAC
* 函数功能：设置DAC输出值
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
void  SetDAC(u16 val)
{
	dac_data_set(DAC0,DAC_OUT1,DAC_ALIGN_12B_R,val);
}
